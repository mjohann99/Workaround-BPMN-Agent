// ======================================================
// MESSAGE FLOWS
// ======================================================
//
// SequenceFlow:
//     within one participant / pool
//
// MessageFlow:
//     between different participants / pools
// ======================================================

export type MessageFlow = {
  id: string;

  fromParticipantId: string;

  toParticipantId: string;

  /**
   * Optional concrete source / target flow nodes.
   *
   * Example:
   * task_send_order -> participant_supplier
   */
  sourceElementId?: string;

  targetElementId?: string;

  name?: string;
};

export type MessageFlowDraft = {
  id?: string;

  tempRef?: string;

  /**
   * Can reference stable participant IDs
   * or participant tempRefs.
   */
  fromParticipantRef: string;

  toParticipantRef: string;

  /**
   * Can reference stable element IDs
   * or element tempRefs.
   */
  sourceElementRef?: string;

  targetElementRef?: string;

  name?: string;
};


// ======================================================
// PROCESS MODEL
// ======================================================

export type ProcessModel = {
  id: string;

  name: string;

  status: ProcessStatus;

  /**
   * BPMN pools / participants.
   */
  participants: Participant[];

  /**
   * Responsibility structure inside participants.
   */
  lanes: Lane[];

  elements: ProcessElement[];

  /**
   * Control flow inside a participant.
   */
  flows: SequenceFlow[];

  /**
   * Communication across participant boundaries.
   */
  messageFlows: MessageFlow[];

  workarounds: WorkaroundCandidate[];

  updatedAt: string;
};


