// ======================================================
// PROCESS STATUS
// ======================================================

export type ProcessStatus =
  | "eliciting"
  | "review"
  | "confirmed";


// ======================================================
// ORGANIZATIONAL STRUCTURE
// ======================================================

export type ParticipantType =
  | "internal"
  | "external"
  | "system";

export type ProcessVisibility =
  | "white_box"
  | "black_box";

export type Participant = {
  id: string;

  name: string;

  /**
   * internal:
   *   Own organization / organizational participant.
   *
   * external:
   *   Customer, supplier, authority, partner, etc.
   *
   * system:
   *   Only use when a system is modeled as an
   *   independent BPMN participant.
   */
  type: ParticipantType;

  /**
   * white_box:
   *   Internal process behavior is modeled.
   *
   * black_box:
   *   Only the participant and message interaction
   *   are relevant.
   */
  processVisibility: ProcessVisibility;
};

export type ParticipantDraft = {
  /**
   * Temporary reference generated by the LLM.
   * Example: "participant_customer"
   */
  tempRef: string;

  name: string;

  type: ParticipantType;

  processVisibility: ProcessVisibility;
};

export type ParticipantUpdate = {
  id: string;

  name?: string;

  type?: ParticipantType;

  processVisibility?: ProcessVisibility;
};


// ======================================================
// LANES
// ======================================================

export type LaneType =
  | "role"
  | "department"
  | "team"
  | "system";

export type Lane = {
  id: string;

  /**
   * Stable ID of the participant / pool
   * this lane belongs to.
   */
  participantId: string;

  name: string;

  type: LaneType;
};

export type LaneDraft = {
  /**
   * Temporary reference generated by the LLM.
   * Example: "lane_accounting"
   */
  tempRef: string;

  /**
   * May reference either:
   * - an existing participant ID
   * - a participant tempRef created in the same response
   */
  participantRef: string;

  name: string;

  type: LaneType;
};

export type LaneUpdate = {
  id: string;

  name?: string;

  type?: LaneType;

  /**
   * Allows moving the lane to another participant
   * if this is ever required by a correction.
   */
  participantId?: string;

  participantRef?: string;
};


