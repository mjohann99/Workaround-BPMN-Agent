// ======================================================
// PROCESS ELEMENTS
// ======================================================

type ProcessElementBase = {
  id: string;

  name: string;

  /**
   * Pool / participant in which this flow node exists.
   *
   * Initially optional because organizational
   * information may not yet have been elicited.
   */
  participantId?: string;

  /**
   * Lane responsible for this flow node.
   *
   * Optional until responsibility is known.
   */
  laneId?: string;
};

export type ProcessElement =
  | (
      ProcessElementBase & {
        type: "start";
      }
    )
  | (
      ProcessElementBase & {
        type: "task";

        /**
         * Concrete human/role mentioned by the employee.
         * Example:
         * "Sachbearbeiter"
         *
         * This is different from laneId.
         */
        performer?: string;

        /**
         * Tool used while performing the activity.
         * Example:
         * SAP, Excel, Salesforce
         */
        system?: string;

        /**
         * Whether the task is mainly executed by a human,
         * automatically by a system, or both.
         */
        executionType?: ExecutionType;

        employeeConfirmed?: boolean;

        // ----------------------------------------------
        // Legacy workaround fields
        // ----------------------------------------------
        //
        // process.workarounds remains the preferred
        // source of truth.
        // ----------------------------------------------

        workaroundCandidate?: boolean;

        workaroundConfirmed?: boolean;

        workaroundReason?: string;

        workaroundCategory?: WorkaroundCategory;
      }
    )
  | (
      ProcessElementBase & {
        type: "exclusiveGateway";
      }
    )
  | (
      ProcessElementBase & {
        type: "end";
      }
    );


