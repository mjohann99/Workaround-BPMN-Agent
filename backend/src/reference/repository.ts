const CURRENT_FILE =
  fileURLToPath(
    import.meta.url
  );

const CURRENT_DIRECTORY =
  path.dirname(
    CURRENT_FILE
  );

const REFERENCE_PROCESS_ROOT =
  path.resolve(
    CURRENT_DIRECTORY,
    "../../data/reference-processes"
  );


// ======================================================
// TIME
// ======================================================

function nowIso():
  string {
  return new Date()
    .toISOString();
}


// ======================================================
// DIRECTORY INITIALIZATION
// ======================================================

async function ensureRepositoryDirectory():
  Promise<void> {
  await mkdir(
    REFERENCE_PROCESS_ROOT,
    {
      recursive:
        true
    }
  );
}


// ======================================================
// REFERENCE ID VALIDATION
// ======================================================
//
// Never insert an arbitrary request parameter directly
// into a filesystem path.
//
// IDs generated by this repository contain only:
//
// a-z
// 0-9
// -
// ======================================================

function isSafeReferenceId(
  id: string
): boolean {
  return /^[a-z0-9-]+$/i.test(
    id
  );
}


function assertSafeReferenceId(
  id: string
): void {
  if (
    !isSafeReferenceId(
      id
    )
  ) {
    throw new Error(
      `Invalid reference process ID: ${id}`
    );
  }
}


// ======================================================
// PATH HELPERS
// ======================================================

function referenceDirectory(
  id: string
): string {
  assertSafeReferenceId(
    id
  );

  return path.join(
    REFERENCE_PROCESS_ROOT,
    id
  );
}


function metadataPath(
  id: string
): string {
  return path.join(
    referenceDirectory(
      id
    ),
    "metadata.json"
  );
}


function versionsDirectory(
  id: string
): string {
  return path.join(
    referenceDirectory(
      id
    ),
    "versions"
  );
}


function versionDirectory(
  id: string,
  version: number
): string {
  return path.join(
    versionsDirectory(
      id
    ),
    String(
      version
    )
  );
}


function versionProcessPath(
  id: string,
  version: number
): string {
  return path.join(
    versionDirectory(
      id,
      version
    ),
    "process.json"
  );
}


function versionBpmnPath(
  id: string,
  version: number
): string {
  return path.join(
    versionDirectory(
      id,
      version
    ),
    "model.bpmn"
  );
}


// ======================================================
// JSON
// ======================================================

async function readJson<T>(
  filePath: string
): Promise<T> {
  const content =
    await readFile(
      filePath,
      "utf8"
    );

  return JSON.parse(
    content
  ) as T;
}


// ======================================================
// ATOMIC WRITE
// ======================================================
//
// Metadata is particularly important because it points
// to the current version.
//
// We first write a temporary file and then rename it.
//
// On Windows replacing an existing target can
// occasionally fail with EPERM / EEXIST, therefore a
// small fallback is included.
// ======================================================

async function writeAtomic(
  filePath: string,
  content: string
): Promise<void> {
  const directory =
    path.dirname(
      filePath
    );

  await mkdir(
    directory,
    {
      recursive:
        true
    }
  );

  const temporaryPath =
    `${filePath}.${randomUUID()}.tmp`;

  await writeFile(
    temporaryPath,
    content,
    "utf8"
  );

  try {
    await rename(
      temporaryPath,
      filePath
    );
  } catch (
    error: unknown
  ) {
    const code =
      error &&
      typeof error ===
        "object" &&
      "code" in error
        ? String(
            error.code
          )
        : undefined;

    if (
      code !== "EPERM" &&
      code !== "EEXIST"
    ) {
      await rm(
        temporaryPath,
        {
          force:
            true
        }
      );

      throw error;
    }

    /**
     * Windows fallback.
     */
    await rm(
      filePath,
      {
        force:
          true
      }
    );

    await rename(
      temporaryPath,
      filePath
    );
  }
}


async function writeJsonAtomic(
  filePath: string,
  value: unknown
): Promise<void> {
  await writeAtomic(
    filePath,
    JSON.stringify(
      value,
      null,
      2
    ) + "\n"
  );
}


// ======================================================
// NORMALIZATION
// ======================================================

function normalizeName(
  name: string
): string {
  const normalized =
    name.trim();

  if (
    !normalized
  ) {
    throw new Error(
      "Reference process name must not be empty"
    );
  }

  return normalized;
}


function normalizeDescription(
  value:
    string |
    undefined
): string | undefined {
  if (
    value === undefined
  ) {
    return undefined;
  }

  const normalized =
    value.trim();

  return normalized ||
    undefined;
}


function normalizeAliases(
  aliases:
    string[] |
    undefined
): string[] {
  if (
    !aliases
  ) {
    return [];
  }

  const normalized =
    aliases
      .map(
        (alias) =>
          alias.trim()
      )
      .filter(Boolean);

  /**
   * Avoid duplicate aliases.
   */
  return [
    ...new Set(
      normalized
    )
  ];
}


// ======================================================
// SLUG
// ======================================================

function createSlug(
  name: string
): string {
  const slug =
    name
      .trim()
      .toLowerCase()
      .normalize("NFD")
      .replace(
        /[\u0300-\u036f]/g,
        ""
      )
      .replace(
        /ß/g,
        "ss"
      )
      .replace(
        /[^a-z0-9]+/g,
        "-"
      )
      .replace(
        /^-+|-+$/g,
        ""
      );

  return slug ||
    "reference-process";
}


function createReferenceId(
  name: string
): string {
  return [
    createSlug(
      name
    ),
    randomUUID()
      .slice(
        0,
        8
      )
  ].join("-");
}


// ======================================================
// REFERENCE PROCESS SANITIZATION
// ======================================================
//
// A reference process is a target / standard process.
//
// It must never contain:
//
// - employee workaround candidates
// - confirmed employee workarounds
// - workaround reasons
// - workaround categories
//
// These belong to interview analysis, not reference
// process definitions.
// ======================================================

function sanitizeReferenceProcess(
  process: ProcessModel,
  options?: {
    processId?: string;
    processName?: string;
  }
): ProcessModel {
  const cleanElements =
    process.elements.map(
      (
        element
      ) => {
        if (
          element.type !==
          "task"
        ) {
          return {
            ...element
          };
        }

        const {
          workaroundCandidate:
            _workaroundCandidate,

          workaroundConfirmed:
            _workaroundConfirmed,

          workaroundReason:
            _workaroundReason,

          workaroundCategory:
            _workaroundCategory,

          ...cleanTask
        } =
          element;

        return cleanTask;
      }
    ) as ProcessModel[
      "elements"
    ];

  return {
    ...structuredClone(
      process
    ),

    id:
      options?.processId ??
      process.id,

    name:
      options?.processName ??
      process.name,

    elements:
      cleanElements,

    workarounds:
      [],

    updatedAt:
      nowIso()
  };
}


// ======================================================
// SEMANTIC MODEL HASH
// ======================================================
//
// updatedAt is deliberately excluded.
//
// Otherwise saving the exact same model at another time
// would create a different hash.
//
// Workarounds are excluded because reference models do
// not contain them anyway.
// ======================================================

function createModelHash(
  process: ProcessModel
): string {
  const semanticModel = {
    id:
      process.id,

    name:
      process.name,

    status:
      process.status,

    participants:
      process.participants,

    lanes:
      process.lanes,

    elements:
      process.elements,

    flows:
      process.flows,

    messageFlows:
      process.messageFlows
  };

  return createHash(
    "sha256"
  )
    .update(
      JSON.stringify(
        semanticModel
      ),
      "utf8"
    )
    .digest(
      "hex"
    );
}


// ======================================================
// READ METADATA
// ======================================================

async function readMetadata(
  id: string
): Promise<
  ReferenceProcessMetadata |
  undefined
> {
  if (
    !isSafeReferenceId(
      id
    )
  ) {
    return undefined;
  }

  try {
    return await readJson<
      ReferenceProcessMetadata
    >(
      metadataPath(
        id
      )
    );
  } catch (
    error: unknown
  ) {
    const code =
      error &&
      typeof error ===
        "object" &&
      "code" in error
        ? String(
            error.code
          )
        : undefined;

    if (
      code === "ENOENT"
    ) {
      return undefined;
    }

    throw error;
  }
}


// ======================================================
// READ VERSION
// ======================================================

async function readVersion(
  id: string,
  version: number
): Promise<
  ReferenceProcessVersion |
  undefined
> {
  if (
    !Number.isInteger(
      version
    ) ||
    version < 1
  ) {
    return undefined;
  }

  try {
    const [
      process,
      bpmnXml
    ] =
      await Promise.all([
        readJson<
          ProcessModel
        >(
          versionProcessPath(
            id,
            version
          )
        ),

        readFile(
          versionBpmnPath(
            id,
            version
          ),
          "utf8"
        )
      ]);

    /**
     * Detect manually corrupted reference files early.
     */
    validateProcessModel(
      process
    );

    return {
      referenceProcessId:
        id,

      version,

      modelHash:
        createModelHash(
          process
        ),

      process,

      bpmnXml,

      /**
       * We currently derive this from the process'
       * updatedAt field.
       *
       * If you later want an immutable dedicated
       * version timestamp, add version.json.
       */
      createdAt:
        process.updatedAt
    };
  } catch (
    error: unknown
  ) {
    const code =
      error &&
      typeof error ===
        "object" &&
      "code" in error
        ? String(
            error.code
          )
        : undefined;

    if (
      code === "ENOENT"
    ) {
      return undefined;
    }

    throw error;
  }
}


// ======================================================
// LIST REFERENCE PROCESSES
// ======================================================

export async function listReferenceProcesses():
  Promise<
    ReferenceProcessSummary[]
  > {
  await ensureRepositoryDirectory();

  const entries =
    await readdir(
      REFERENCE_PROCESS_ROOT,
      {
        withFileTypes:
          true
      }
    );

  const summaries:
    ReferenceProcessSummary[] =
    [];

  for (
    const entry of
    entries
  ) {
    if (
      !entry.isDirectory()
    ) {
      continue;
    }

    if (
      !isSafeReferenceId(
        entry.name
      )
    ) {
      continue;
    }

    const metadata =
      await readMetadata(
        entry.name
      );

    /**
     * Ignore directories that are not valid reference
     * process records.
     */
    if (
      !metadata
    ) {
      continue;
    }

    summaries.push({
      id:
        metadata.id,

      name:
        metadata.name,

      aliases: [
        ...metadata.aliases
      ],

      description:
        metadata.description,

      active:
        metadata.active,

      currentVersion:
        metadata.currentVersion,

      updatedAt:
        metadata.updatedAt

      /**
       * assignedSessionCount and openDeviationCount
       * intentionally do NOT belong to filesystem
       * persistence.
       *
       * They are runtime aggregations from InterviewSession
       * and should be added by the Owner API.
       */
    });
  }

  summaries.sort(
    (
      left,
      right
    ) =>
      left.name.localeCompare(
        right.name,
        "de"
      )
  );

  return summaries;
}


// ======================================================
// GET REFERENCE PROCESS
// ======================================================
//
// If version is omitted:
// -> current version
//
// If version is supplied:
// -> exact historical version
//
// Note:
//
// metadata.currentVersion always indicates the newest
// stored version.
//
// record.currentVersion contains the version requested
// by this function.
//
// The property name is slightly historical, but keeping
// it avoids changing the frontend structure now.
// ======================================================

export async function getReferenceProcess(
  id: string,
  version?: number
): Promise<
  ReferenceProcessRecord |
  undefined
> {
  await ensureRepositoryDirectory();

  const metadata =
    await readMetadata(
      id
    );

  if (
    !metadata
  ) {
    return undefined;
  }

  const requestedVersion =
    version ??
    metadata.currentVersion;

  const referenceVersion =
    await readVersion(
      id,
      requestedVersion
    );

  if (
    !referenceVersion
  ) {
    return undefined;
  }

  return {
    metadata:
      structuredClone(
        metadata
      ),

    currentVersion:
      referenceVersion
  };
}


// ======================================================
// CREATE REFERENCE PROCESS
// ======================================================
//
// Creates:
//
// metadata.json
//
// versions/1/process.json
// versions/1/model.bpmn
// ======================================================

export async function createReferenceProcess(
  input:
    CreateReferenceProcessInput
): Promise<
  ReferenceProcessRecord
> {
  await ensureRepositoryDirectory();

  const name =
    normalizeName(
      input.name
    );

  const aliases =
    normalizeAliases(
      input.aliases
    );

  const description =
    normalizeDescription(
      input.description
    );

  const id =
    createReferenceId(
      name
    );

  const timestamp =
    nowIso();

  // ----------------------------------------------------
  // INITIAL REFERENCE MODEL
  // ----------------------------------------------------

  const initialProcess =
    createInitialProcess(
      name
    );

  const cleanProcess =
    sanitizeReferenceProcess(
      initialProcess,
      {
        processName:
          name
      }
    );

  validateProcessModel(
    cleanProcess
  );

  const bpmnXml =
    generateBpmnXml(
      cleanProcess
    );

  const modelHash =
    createModelHash(
      cleanProcess
    );

  // ----------------------------------------------------
  // METADATA
  // ----------------------------------------------------

  const metadata:
    ReferenceProcessMetadata = {
    id,

    name,

    aliases,

    ...(description
      ? {
          description
        }
      : {}),

    active:
      true,

    currentVersion:
      1,

    createdAt:
      timestamp,

    updatedAt:
      timestamp
  };

  // ----------------------------------------------------
  // VERSION 1
  // ----------------------------------------------------

  const referenceVersion:
    ReferenceProcessVersion = {
    referenceProcessId:
      id,

    version:
      1,

    modelHash,

    process:
      cleanProcess,

    bpmnXml,

    createdAt:
      timestamp
  };

  // ----------------------------------------------------
  // CREATE DIRECTORIES
  // ----------------------------------------------------

  await mkdir(
    versionDirectory(
      id,
      1
    ),
    {
      recursive:
        true
    }
  );

  // ----------------------------------------------------
  // WRITE VERSION FIRST
  // ----------------------------------------------------
  //
  // metadata.json is written last so metadata never
  // points to a version that has not yet been written.
  // ----------------------------------------------------

  await writeJsonAtomic(
    versionProcessPath(
      id,
      1
    ),
    cleanProcess
  );

  await writeAtomic(
    versionBpmnPath(
      id,
      1
    ),
    bpmnXml
  );

  await writeJsonAtomic(
    metadataPath(
      id
    ),
    metadata
  );

  return {
    metadata:
      structuredClone(
        metadata
      ),

    currentVersion:
      structuredClone(
        referenceVersion
      )
  };
}


// ======================================================
// UPDATE REFERENCE METADATA
// ======================================================
//
// Changing:
//
// - name
// - aliases
// - description
// - active
//
// does NOT create a new process model version.
//
// Structural BPMN changes use:
//
// saveReferenceProcessVersion()
// ======================================================

export async function updateReferenceMetadata(
  id: string,
  patch:
    UpdateReferenceMetadataInput
): Promise<
  ReferenceProcessRecord
> {
  const current =
    await getReferenceProcess(
      id
    );

  if (
    !current
  ) {
    throw new Error(
      `Reference process not found: ${id}`
    );
  }

  const currentMetadata =
    current.metadata;

  const updatedMetadata:
    ReferenceProcessMetadata = {
    ...currentMetadata,

    name:
      patch.name !==
      undefined
        ? normalizeName(
            patch.name
          )
        : currentMetadata.name,

    aliases:
      patch.aliases !==
      undefined
        ? normalizeAliases(
            patch.aliases
          )
        : [
            ...currentMetadata
              .aliases
          ],

    active:
      patch.active !==
      undefined
        ? patch.active
        : currentMetadata.active,

    updatedAt:
      nowIso()
  };

  // ----------------------------------------------------
  // DESCRIPTION
  // ----------------------------------------------------
  //
  // description: ""
  //
  // means:
  //
  // remove existing description.
  // ----------------------------------------------------

  if (
    patch.description !==
    undefined
  ) {
    const description =
      normalizeDescription(
        patch.description
      );

    if (
      description
    ) {
      updatedMetadata.description =
        description;
    } else {
      delete updatedMetadata
        .description;
    }
  }

  await writeJsonAtomic(
    metadataPath(
      id
    ),
    updatedMetadata
  );

  const updated =
    await getReferenceProcess(
      id
    );

  if (
    !updated
  ) {
    throw new Error(
      `Failed to reload reference process: ${id}`
    );
  }

  return updated;
}


// ======================================================
// SAVE NEW REFERENCE PROCESS VERSION
// ======================================================
//
// Called only when the Process Owner explicitly saves
// BPMN model changes.
//
// Example:
//
// Version 2
// -> edit BPMN
// -> "Neue Version speichern"
// -> Version 3
//
// A metadata rename does NOT call this.
// ======================================================

export async function saveReferenceProcessVersion(
  id: string,
  process:
    ProcessModel
): Promise<
  ReferenceProcessRecord
> {
  const current =
    await getReferenceProcess(
      id
    );

  if (
    !current
  ) {
    throw new Error(
      `Reference process not found: ${id}`
    );
  }

  const currentProcess =
    current.currentVersion
      .process;

  // ----------------------------------------------------
  // SANITIZE
  // ----------------------------------------------------
  //
  // Keep the BPMN process ID stable across versions.
  //
  // Keep the owner-controlled metadata name as the
  // process name.
  // ----------------------------------------------------

  const cleanProcess =
    sanitizeReferenceProcess(
      process,
      {
        processId:
          currentProcess.id,

        processName:
          current.metadata.name
      }
    );

  validateProcessModel(
    cleanProcess
  );

  // ----------------------------------------------------
  // HASH
  // ----------------------------------------------------

  const newModelHash =
    createModelHash(
      cleanProcess
    );

  // ----------------------------------------------------
  // NO-OP SAVE
  // ----------------------------------------------------
  //
  // Do not create another version when no semantic
  // process change actually occurred.
  // ----------------------------------------------------

  if (
    newModelHash ===
    current.currentVersion
      .modelHash
  ) {
    return current;
  }

  const nextVersion =
    current.metadata
      .currentVersion +
    1;

  const timestamp =
    nowIso();

  const versionProcess:
    ProcessModel = {
    ...cleanProcess,

    updatedAt:
      timestamp
  };

  const bpmnXml =
    generateBpmnXml(
      versionProcess
    );

  const referenceVersion:
    ReferenceProcessVersion = {
    referenceProcessId:
      id,

    version:
      nextVersion,

    modelHash:
      newModelHash,

    process:
      versionProcess,

    bpmnXml,

    createdAt:
      timestamp
  };

  // ----------------------------------------------------
  // CREATE VERSION DIRECTORY
  // ----------------------------------------------------

  await mkdir(
    versionDirectory(
      id,
      nextVersion
    ),
    {
      recursive:
        true
    }
  );

  // ----------------------------------------------------
  // WRITE VERSION
  // ----------------------------------------------------

  await writeJsonAtomic(
    versionProcessPath(
      id,
      nextVersion
    ),
    versionProcess
  );

  await writeAtomic(
    versionBpmnPath(
      id,
      nextVersion
    ),
    bpmnXml
  );

  // ----------------------------------------------------
  // UPDATE METADATA LAST
  // ----------------------------------------------------

  const updatedMetadata:
    ReferenceProcessMetadata = {
    ...current.metadata,

    currentVersion:
      nextVersion,

    updatedAt:
      timestamp
  };

  await writeJsonAtomic(
    metadataPath(
      id
    ),
    updatedMetadata
  );

  return {
    metadata:
      structuredClone(
        updatedMetadata
      ),

    currentVersion:
      structuredClone(
        referenceVersion
      )
  };
}

// ======================================================
// DELETE REFERENCE PROCESS
// ======================================================
//
// Permanently removes:
//
// backend/data/reference-processes/<id>/
//
// including:
//
// - metadata.json
// - all process.json versions
// - all model.bpmn versions
//
// IMPORTANT:
//
// Whether the reference process is still assigned to
// employee sessions is checked by the Owner API before
// this repository function is called.
//
// The repository itself only owns filesystem
// persistence.
// ======================================================

export async function deleteReferenceProcess(
  id:
    string
): Promise<void> {
  // ----------------------------------------------------
  // SECURITY
  // ----------------------------------------------------
  //
  // Prevent arbitrary filesystem paths from being
  // supplied as reference-process IDs.
  // ----------------------------------------------------

  assertSafeReferenceId(
    id
  );


  // ----------------------------------------------------
  // REFERENCE MUST EXIST
  // ----------------------------------------------------

  const existing =
    await getReferenceProcess(
      id
    );

  if (
    !existing
  ) {
    throw new Error(
      `Reference process not found: ${id}`
    );
  }


  // ----------------------------------------------------
  // DELETE COMPLETE REFERENCE DIRECTORY
  // ----------------------------------------------------

  const directory =
    referenceDirectory(
      id
    );

  await rm(
    directory,
    {
      recursive:
        true,

      force:
        false
    }
  );
}


// ======================================================
// LIST ACTIVE REFERENCE PROCESSES
// ======================================================
//
// Convenience function for automatic process
// identification later.
//
// The matcher should only consider active reference
// processes.
// ======================================================

export async function listActiveReferenceProcesses():
  Promise<
    ReferenceProcessRecord[]
  > {
  const summaries =
    await listReferenceProcesses();

  const active =
    summaries.filter(
      (summary) =>
        summary.active
    );

  const records =
    await Promise.all(
      active.map(
        (summary) =>
          getReferenceProcess(
            summary.id
          )
      )
    );

  return records.filter(
    (
      record
    ): record is
      ReferenceProcessRecord =>
      record !==
      undefined
  );
}